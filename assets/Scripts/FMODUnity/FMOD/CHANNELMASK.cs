using System;

namespace FMOD;

[Flags]
public enum CHANNELMASK : uint
{
	FRONT_LEFT = 1u,
	FRONT_RIGHT = 2u,
	FRONT_CENTER = 4u,
	LOW_FREQUENCY = 8u,
	SURROUND_LEFT = 0x10u,
	SURROUND_RIGHT = 0x20u,
	BACK_LEFT = 0x40u,
	BACK_RIGHT = 0x80u,
	BACK_CENTER = 0x100u,
	MONO = FRONT_LEFT,
	STEREO = FRONT_LEFT | FRONT_RIGHT,
	LRC = STEREO | FRONT_CENTER,
	QUAD = STEREO | SURROUND_LEFT | SURROUND_RIGHT,
	SURROUND = QUAD | FRONT_CENTER,
	_5POINT1 = SURROUND | LOW_FREQUENCY,
	_5POINT1_REARS = LRC | LOW_FREQUENCY | BACK_LEFT | BACK_RIGHT,
	_7POINT0 = SURROUND | BACK_LEFT | BACK_RIGHT,
	_7POINT1 = _7POINT0 | LOW_FREQUENCY
}
